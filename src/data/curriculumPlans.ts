// 과목 및 평가영역/요소로 해당 계획 아이템 찾기 헬퍼
export function findCurriculumPlan(subject: string, evalArea: string, evalElement?: string): CurriculumPlanItem | undefined {
  if (evalElement) {
    const exact = CURRICULUM_EVAL_PLANS.find(
      (p) => p.subject === subject && (p.evalArea === evalArea || p.evalArea.includes(evalArea)) && p.evalElement.includes(evalElement)
    );
    if (exact) return exact;
  }
  return CURRICULUM_EVAL_PLANS.find(
    (p) => p.subject === subject && (p.evalArea === evalArea || p.evalArea.includes(evalArea))
  );
}
