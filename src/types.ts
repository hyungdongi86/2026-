export interface GradeRecord {
  id: string;
  studentId: string;
  studentName: string;
  subject: string;       // 교과목명 (도덕, 국어, 수학, 사회, 과학, 음악, 미술, 체육, 실과, 영어)
  testType?: TestType | string;
  score: number;         // 취득 점수
  maxScore: number;      // 만점 (기본값 100)
  performanceRating?: PerformanceLevel; // 수행평가 4단계 기준 ('매우잘함' | '잘함' | '보통' | '노력 요함')
  evalArea?: string;     // 평가 영역 (예: 문학, 수와 연산 등)
  evalElement?: string;  // 연계 평가 요소
  semester?: string;     // 하위호환 학기
  testDate?: string;     // 평가일자
  teacherComment?: string; // 교사 한줄평 / 피드백
}

